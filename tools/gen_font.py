"""Generate a 1-bit monospace bitmap font (ASCII + Cyrillic) for the eye UI.

Outputs:
  firmware/.../main/boards/zhengchen-1.54tft-wifi/cv_font.h   (C table for the device)
  proto/cv_font.js                      (same data for the browser prototype)
uv run python tools/gen_font.py [--preview]
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = "C:/Windows/Fonts/consola.ttf"
CELL_W, CELL_H, SIZE, BASE_Y = 8, 12, 12, 0

CHARS = "".join(chr(c) for c in range(32, 127)) + \
    "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя" + "°…▶█▮·—«»№"


def render():
    font = ImageFont.truetype(FONT, SIZE)
    glyphs = {}
    for ch in CHARS:
        img = Image.new("1", (CELL_W, CELL_H), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((0, BASE_Y), ch, font=font, fill=1)
        rows = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if img.getpixel((x, y)):
                    bits |= 0x80 >> x
            rows.append(bits)
        glyphs[ch] = rows
    return glyphs


def main():
    glyphs = render()
    if "--preview" in sys.argv:
        for ch in "Привет ЖЩЫ 76% ▶_":
            print("\n".join("".join("#" if r & (0x80 >> x) else "." for x in range(CELL_W))
                            for r in glyphs[ch]))
            print()
        return
    codes = sorted(ord(c) for c in glyphs)
    # C header
    lines = [f"// Generated by tools/gen_font.py from Consolas {SIZE}px. Do not edit.",
             "#pragma once", "#include <stdint.h>",
             f"#define CV_FONT_W {CELL_W}", f"#define CV_FONT_H {CELL_H}",
             f"#define CV_FONT_COUNT {len(codes)}",
             "static const uint16_t cv_font_codes[CV_FONT_COUNT] = {",
             "    " + ", ".join(str(c) for c in codes), "};",
             f"static const uint8_t cv_font_bits[CV_FONT_COUNT][CV_FONT_H] = {{"]
    for c in codes:
        lines.append("    {" + ", ".join(f"0x{b:02x}" for b in glyphs[chr(c)]) + "},")
    lines.append("};")
    hdr = ROOT / "firmware/xiaozhi-esp32/main/boards/zhengchen-1.54tft-wifi/cv_font.h"
    hdr.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # JS
    js = ROOT / "proto/cv_font.js"
    js.parent.mkdir(exist_ok=True)
    data = ",".join(f"{c}:[{','.join(str(b) for b in glyphs[chr(c)])}]" for c in codes)
    js.write_text(f"// Generated by tools/gen_font.py\nconst CV_FONT={{w:{CELL_W},h:{CELL_H},g:{{{data}}}}};\n",
                  encoding="utf-8")
    print(f"{len(codes)} glyphs -> {hdr.relative_to(ROOT)}, {js.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
